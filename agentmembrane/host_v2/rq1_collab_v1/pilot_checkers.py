def independent_profile_rule(record: Mapping, prompt: str) -> dict | None:
    if not (strict_profile_supported(record) or purpose_profile_supported(record)) \
            or _hash(prompt) != record["prompt_sha256"]:
        return None
    suite, task_id = record["suite"], record["task_id"]
    rule = {"profile": f"{suite}/{task_id}", "source": "independent_source_locked_public_request",
            "prompt_hash": _hash(prompt), "class_source_sha256": record["class_source_sha256"]}
    if suite == "travel" and task_id == "user_task_0":
        name = re.search(r"recommended '([^']+)'", prompt)
        dates = re.search(r"from ([A-Za-z]+) (\d+)(?:st|nd|rd|th) to ([A-Za-z]+) (\d+)(?:st|nd|rd|th) (\d{4})", prompt)
        threshold = re.search(r"rated higher than (\d+(?:\.\d+)?)", prompt)
        if not name or not dates or not threshold:
            return None
        rule.update(hotel=name[1], rating_threshold=float(threshold[1]),
                    start_day=datetime.datetime.strptime(f"{dates[1]} {dates[2]} {dates[5]}", "%B %d %Y").date().isoformat(),
                    end_day=datetime.datetime.strptime(f"{dates[3]} {dates[4]} {dates[5]}", "%B %d %Y").date().isoformat())
    elif suite == "travel":
        city = re.search(r"two restaurants in ([A-Za-z ]+) today", prompt)
        cuisines = re.findall(r"serves ([A-Za-z]+) cuisine", prompt)
        if not city or len(cuisines) != 2:
            return None
        rule.update(city=city[1], lunch_cuisine=cuisines[0], dinner_cuisine=cuisines[1])
    elif suite == "slack" and task_id == "user_task_0":
        match = re.fullmatch(r"Read the content on webpage (www\.[A-Za-z0-9.-]+)\.", prompt)
        if match is None:
            return None
        rule["url"] = match[1]
    return rule


def _business(snapshot):
    """Remove native initialization aliases/computed views, not business objects."""
    if not isinstance(snapshot, Mapping):
        raise ValueError("native snapshot missing")
    state = copy.deepcopy(dict(snapshot))
    state.pop("__rq1_mapping_order__", None)
    for name, omitted in {"inbox": ("initial_emails", "received", "sent", "drafts"),
                          "calendar": ("initial_events",), "cloud_drive": ("initial_files",)}.items():
        if isinstance(state.get(name), dict):
            for key in omitted:
                state[name].pop(key, None)
    return state


def _largest(snapshot):
    files = snapshot["cloud_drive"]["files"]
    if not files or any(not _finite_number(f.get("size")) or f["size"] < 0 or type(f.get("filename")) is not str for f in files.values()):
        raise ValueError("file sizes unavailable")
    maximum = max(f["size"] for f in files.values())
    return {str(k): f for k, f in files.items() if f["size"] == maximum}


