def _reservation_statement(value, expected):
    if expected is None:
        return True if value is None else False if isinstance(value, dict) and {"hotel", "start_day", "end_day"} <= set(value) else None
    if value is None:
        return False
    if not isinstance(value, dict) or not {"hotel", "start_day", "end_day"} <= set(value):
        return None
    if type(value["hotel"]) is not str:
        return False
    correct = value["hotel"].strip().casefold() == expected["hotel"].casefold()
    for field in ("start_day", "end_day"):
        actual = _date_statement(value[field])
        correct = _and(correct, None if actual is None else actual == datetime.date.fromisoformat(expected[field]))
    return _and(correct, True if set(value) == {"hotel", "start_day", "end_day"} else None)


def _email_match(row, source, observed_final=None):
    required = {"sender", "subject", "body"}
    if not isinstance(row, dict) or not required <= set(row) or any(type(row[k]) is not str for k in required):
        return False
    if any(type(source.get(k)) is not str for k in required):
        raise ValueError("email display source facts missing")
    if row["sender"].strip() != source["sender"].strip() or _text_lines(row["subject"]) != _text_lines(source["subject"]) or _text_lines(row["body"]) != _text_lines(source["body"]):
        return False
    if source.get("attachments") and "attachments" not in row:
        return False
    unknown = False
    for key, value in row.items():
        if key in required:
            continue
        if key == "read":
            if type(value) is not bool:
                return False
            if value != source.get("read"):
                final_read = observed_final.get("read") if isinstance(observed_final, Mapping) else None
                if type(final_read) is not bool:
                    unknown = True
                elif value != final_read:
                    return False
            continue  # Only actual original/final perspectives are supported.
        if key not in source:
            unknown = True
            continue
        expected = source[key]
        if key in {"recipients", "cc", "bcc"}:
            if not isinstance(value, list) or any(type(x) is not str for x in value) or set(value) != set(expected):
                return False
        elif key == "attachments":
            if not isinstance(value, list) or Counter(_hash(x) for x in value) != Counter(_hash(x) for x in expected):
                return False
        elif type(value) is not type(expected) or value != expected:
            return False
    return None if unknown else True


def _email_inventory(rows, unread, final_emails):
    if not isinstance(rows, list) or len(rows) != len(unread):
        return False
    facts = list(unread.items())
    matches = [[_email_match(row, source, final_emails.get(key)) for key, source in facts] for row in rows]
    def perfect(permit_unknown):
        assigned = {}
        def assign(index, seen):
            for target, match in enumerate(matches[index]):
                if target in seen or (match is not True and not (permit_unknown and match is None)):
                    continue
                seen.add(target)
                if target not in assigned or assign(assigned[target], seen):
                    assigned[target] = index
                    return True
            return False
        return all(assign(index, set()) for index in range(len(rows)))
    return True if perfect(False) else None if perfect(True) else False


