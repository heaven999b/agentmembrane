def _scalar_semantic(answer, status, key, expected, *, numeric=False):
    if status == "empty":
        return False
    if status == "unknown":
        return None
    structured = isinstance(answer, Mapping)
    if structured:
        if set(answer) != {key}:
            return False if key in answer or not answer else None
        answer = answer[key]
    elif status == "json" and isinstance(answer, list):
        return None
    if numeric:
        number = _answer_number(answer)
        return (False if structured else None) if number is None else number == Decimal(str(expected))
    if type(answer) is not str:
        return False
    value = answer.strip().rstrip(".").strip()
    return value.casefold() == expected.casefold()


def _travel_fields(answer, status, fields, legacy=None):
    """Narrow complete answer grammar; never award by substring collection."""
    if status == "empty":
        return False
    if isinstance(answer, Mapping):
        if set(answer) != set(fields):
            return False
        for key, expected in fields.items():
            if type(expected) in (int, float, Decimal):
                if _answer_number(answer[key]) != Decimal(str(expected)):
                    return False
            elif type(answer[key]) is not str or _words(answer[key]).casefold() != _words(expected).casefold():
                return False
        return True
    if type(answer) is str and legacy is not None:
        return _words(answer).casefold() == _words(legacy).casefold()
    return None


def _unique_best(rows, *, rating="rating", price=None, cheaper=False):
    if not rows:
        raise ValueError("recommendation candidates unavailable")
    best_rating = max(_source_number(row[rating]) for row in rows)
    top = [row for row in rows if _source_number(row[rating]) == best_rating]
    if price is not None:
        extreme = (min if cheaper else max)(_source_number(row[price]) for row in top)
        top = [row for row in top if _source_number(row[price]) == extreme]
    if len(top) != 1:
        raise ValueError("recommendation target ambiguous")
    return top[0]


