def _native_read_answer(text):
    """Classify a small, unambiguous answer grammar; unfamiliar prose is unknown."""
    if type(text) is not str or not text.strip():
        return None, "empty"
    stripped = text.strip()
    if stripped[:1] in "{[\"" or re.fullmatch(r"[+-]?\d+(?:\.\d+)?", stripped):
        parsed, error = _answer(stripped)
        return (parsed, "json") if error is None else (None, "unknown")
    return stripped, "text"


